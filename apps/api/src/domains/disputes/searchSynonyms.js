// 단어가 동사(VERB_NOUNS)로 시작하면 { form, nouns }, 아니면 null.
export const findVerbNouns = (word) => {
  for (const { forms, nouns } of VERB_NOUNS) {
    const form = forms.find((candidate) => word.startsWith(candidate));
    if (form) return { form, nouns };
  }
  return null;
};

// 단어 경계 오탐 막기: 찾는 말이 뜻이 다른 낱말 속 글자로 걸리는 경우. 자료에서 "첫머리가 아닌 곳에만 나오는 자료"를 세어 골랐다.
// 대부분의 "가운데 일치"는 정상 합성어(임대차보증금·연체차임·계약갱신)라 모든 말에 첫머리 규칙을 걸 수는 없다.
