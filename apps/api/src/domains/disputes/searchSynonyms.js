// 바꿔 찾기 대상인 말인지("복비"). 조사를 뗀 말이 대상이면 원래 말은 찾지 않는다(service.js toBaseWords).
export const isReplacedWord = (word) => Object.hasOwn(REPLACEMENTS, word);

const buildSynonymMap = () => {
  const map = new Map(Object.entries(ONE_WAY_SYNONYMS));
  for (const group of SYNONYM_GROUPS) {
    for (const word of group) {
      map.set(word, [...new Set([...(map.get(word) ?? []), ...group.filter((other) => other !== word)])]);
    }
  }
  return map;
};

const SYNONYMS = buildSynonymMap();

// 단어의 동의어 목록(자기 자신은 빼고). 없으면 [].
export const findSynonyms = (word) => SYNONYMS.get(word) ?? [];

// 두 말이 같은 뜻 묶음(SYNONYM_GROUPS)에 함께 있는지. 같은 뜻이면 한 방향 동의어보다 점수를 더 준다(service.js).
const GROUP_INDEX = new Map(SYNONYM_GROUPS.flatMap((group, index) => group.map((word) => [word, index])));
export const isSameMeaning = (word, other) => GROUP_INDEX.has(word) && GROUP_INDEX.get(word) === GROUP_INDEX.get(other);
